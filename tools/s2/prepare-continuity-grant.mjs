#!/usr/bin/env node
/** Offline administrator tool. It never reads credentials, changes ACLs, or claims a repository. */
import { createHash } from 'node:crypto';
import { constants } from 'node:fs';
import { open, unlink } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HASH = /^[a-f0-9]{64}$/u;
const UUID = /^[a-f0-9]{8}-[a-f0-9]{4}-[1-8][a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/u;
const IDENTIFIER = /^[^\s\p{Cc}\p{Cf}\p{Cs}/\\%?#|=]+$/u;
const CLAIMS = ['writer-permanently-revoked', 'snapshot-sequence-verified', 'claim-store-atomic-immutable'];
const FIELD_NAMES = ['repositoryUrl', 'instanceId', 'provider', 'endpointHint', 'applicationId', 'versionName',
  'versionCode', 'sourceInstallationId', 'writerId', 'uploadSeq', 'archiveSha256', 'sidecarSha256',
  'targetInstallationId', 'operationId', 'issuedAtEpochSecond', 'expiresAtEpochSecond', 'attestations', 'peerCanonicalIds'];
const MAX_MANAGEMENT_BYTES = 1024 * 1024;
const MAX_ARCHIVE_BYTES = 20 * 1024 ** 3;
const MAX_SIDECAR_BYTES = 8 * 1024 ** 2;
const MAX_LIFETIME = 7 * 24 * 3600;
const MAX_WIRE_SEQUENCE_BEFORE_NEXT_UPLOAD = 999_999_999_998;

function requireThat(condition, code) { if (!condition) throw new Error(code); }
function text(value, limit) {
  return typeof value === 'string' && value.trim().length > 0 && Buffer.byteLength(value, 'utf8') <= limit &&
    !/[\p{Cc}\p{Cf}\p{Cs}]/u.test(value);
}
function identifier(value) { return text(value, 160) && IDENTIFIER.test(value) && value !== '.' && value !== '..'; }
function uint(value, max = Number.MAX_SAFE_INTEGER) { return Number.isSafeInteger(value) && value >= 0 && value <= max; }
function alias(device) { return createHash('sha256').update(device, 'utf8').digest('hex').slice(0, 16); }
function sortedPeers(values, writerId) {
  requireThat(Array.isArray(values) && values.length >= 1 && values.length <= 4096 && values.every(identifier), 'INVALID_PEER_INVENTORY');
  const ordered = values.slice().sort((left, right) => Buffer.compare(Buffer.from(left), Buffer.from(right)));
  requireThat(new Set(ordered).size === ordered.length && ordered.includes(writerId), 'INVALID_PEER_INVENTORY');
  const owners = new Map();
  for (const peer of ordered) for (const id of [peer, alias(peer)]) {
    requireThat(!owners.has(id) || owners.get(id) === peer, 'AMBIGUOUS_PEER');
    owners.set(id, peer);
  }
  return ordered;
}
function webdav(repo, hint) {
  requireThat(text(repo, 2048) && text(hint, 4096), 'INVALID_REPOSITORY');
  let url;
  try { url = new URL(repo); } catch { throw new Error('INVALID_REPOSITORY'); }
  requireThat(url.protocol === 'https:' && !url.username && !url.password && !url.search && !url.hash &&
    url.href === repo && url.pathname.endsWith('/'), 'INVALID_REPOSITORY');
  requireThat(!/[?#]/u.test(hint) && !/(?:^|\|)\s*(?:password|passwd|token|secret|authorization|credential|access[_-]?key|api[_-]?key|private[_-]?key)\s*=/iu.test(hint), 'INVALID_ENDPOINT_HINT');
  for (const part of hint.split('|')) {
    const field = part.includes('=') ? part.slice(part.indexOf('=') + 1) : part;
    if (!field.includes('://')) continue;
    let endpoint;
    try { endpoint = new URL(field); } catch { throw new Error('INVALID_ENDPOINT_HINT'); }
    requireThat(!endpoint.username && !endpoint.password, 'INVALID_ENDPOINT_HINT');
  }
}

/** Input must come from an independent approval record, never be generated by trusting the sidecar. */
export function formatContinuityGrant(approval, now = Math.floor(Date.now() / 1000)) {
  requireThat(approval !== null && typeof approval === 'object' && !Array.isArray(approval), 'INVALID_APPROVAL');
  requireThat(Object.keys(approval).length === FIELD_NAMES.length && FIELD_NAMES.every(k => Object.hasOwn(approval, k)), 'INVALID_APPROVAL');
  const a = approval;
  requireThat([a.instanceId, a.applicationId, a.versionName, a.sourceInstallationId, a.writerId].every(identifier), 'INVALID_IDENTITY');
  requireThat(a.provider === 'WebDAV' || a.provider === 'webdav', 'INVALID_PROVIDER');
  webdav(a.repositoryUrl, a.endpointHint);
  requireThat(uint(a.versionCode) && a.versionCode > 0 && uint(a.uploadSeq, MAX_WIRE_SEQUENCE_BEFORE_NEXT_UPLOAD), 'INVALID_SEQUENCE');
  requireThat(HASH.test(a.archiveSha256) && HASH.test(a.sidecarSha256), 'INVALID_DIGEST');
  requireThat(UUID.test(a.targetInstallationId) && UUID.test(a.operationId), 'INVALID_REQUEST');
  requireThat(uint(a.issuedAtEpochSecond) && uint(a.expiresAtEpochSecond) &&
    a.issuedAtEpochSecond <= now && now < a.expiresAtEpochSecond &&
    a.expiresAtEpochSecond - a.issuedAtEpochSecond <= MAX_LIFETIME, 'INVALID_TIME_WINDOW');
  requireThat(Array.isArray(a.attestations) && a.attestations.length === CLAIMS.length &&
    CLAIMS.every((name, i) => name === a.attestations[i]), 'ACKNOWLEDGEMENTS_REQUIRED');
  const peers = sortedPeers(a.peerCanonicalIds, a.writerId);
  const payload = Buffer.from(['dstu-continuity-grant-v1', ...FIELD_NAMES.slice(0, 16).map(k => a[k]),
    ...CLAIMS, peers.length, ...peers].join('\n') + '\n', 'utf8');
  requireThat(payload.length <= MAX_MANAGEMENT_BYTES, 'APPROVAL_TOO_LARGE');
  return payload;
}

async function source(path, limit, job) {
  const fd = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try {
    const stat = await fd.stat();
    requireThat(stat.isFile() && stat.size > 0 && stat.size <= limit, 'INPUT_SIZE_OR_TYPE');
    return await job(fd, stat.size);
  } finally { await fd.close(); }
}
async function boundedRead(path, limit) {
  return source(path, limit, async (fd, size) => {
    const buffer = Buffer.alloc(size + 1);
    let read = 0;
    while (read < buffer.length) {
      const result = await fd.read(buffer, read, buffer.length - read, read);
      if (!result.bytesRead) break;
      read += result.bytesRead;
    }
    requireThat(read === size, 'INPUT_CHANGED');
    return new TextDecoder('utf-8', { fatal: true }).decode(buffer.subarray(0, read));
  });
}
async function digest(path, limit) {
  return source(path, limit, async (fd, size) => {
    const hash = createHash('sha256');
    let read = 0;
    for await (const chunk of fd.createReadStream({ autoClose: false, start: 0, end: size })) {
      read += chunk.length;
      requireThat(read <= size, 'INPUT_CHANGED');
      hash.update(chunk);
    }
    requireThat(read === size, 'INPUT_CHANGED');
    return hash.digest('hex');
  });
}

export async function prepareContinuityGrant({ approval, archive, sidecar, out }) {
  const approved = JSON.parse(await boundedRead(approval, MAX_MANAGEMENT_BYTES));
  const bytes = formatContinuityGrant(approved);
  requireThat(await digest(archive, MAX_ARCHIVE_BYTES) === approved.archiveSha256, 'ARCHIVE_HASH_MISMATCH');
  requireThat(await digest(sidecar, MAX_SIDECAR_BYTES) === approved.sidecarSha256, 'SIDECAR_HASH_MISMATCH');
  const result = await open(out, 'wx', 0o600);
  try { await result.writeFile(bytes); await result.sync(); }
  catch (error) { await result.close(); await unlink(out); throw error; }
  await result.close();
}

function argumentsOf(args) {
  const values = {};
  const allowed = new Set(['--approval', '--archive', '--sidecar', '--out']);
  requireThat(args.length === 8, 'USAGE');
  for (let i = 0; i < args.length; i += 2) {
    requireThat(allowed.delete(args[i]) && args[i + 1] && !args[i + 1].startsWith('--'), 'USAGE');
    values[args[i].slice(2)] = args[i + 1];
  }
  return values;
}

const USAGE = `Usage: node prepare-continuity-grant.mjs --approval APPROVED.json --archive BACKUP.zip --sidecar MIGRATION.json --out NEW.grant
Approval is an independent administrator record with these exact keys:
${FIELD_NAMES.join(', ')}
attestations must be ${JSON.stringify(CLAIMS)} (verify these operationally before signing).
Dates and sequence are integer seconds/values. peerCanonicalIds is the complete list of device IDs.
The tool only prepares bytes. Separately sign the resulting file with openssl dgst -sha256 -sign ADMIN.pem -out AUTH.sig NEW.grant.
Share only the DER public key and its SHA-256 fingerprint through an independent channel; never include the private key.`;

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length === 3 && process.argv[2] === '--help') console.log(USAGE);
  else try {
    await prepareContinuityGrant(argumentsOf(process.argv.slice(2)));
    console.log('continuity grant prepared; administrator must still verify and sign it');
  } catch (error) {
    const code = typeof error.message === 'string' && /^[A-Z][A-Z0-9_]+$/u.test(error.message) ? error.message : 'INPUT_OR_OUTPUT_ERROR';
    console.error(code === 'USAGE' ? USAGE : `continuity grant not written: ${code}`);
    process.exitCode = 1;
  }
}
