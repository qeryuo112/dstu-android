    private fun fixture(name: String = "legacy-mobile-standard-standard-v1.zip"): File {
        var current: File? = File("").absoluteFile
        while (current != null) {
            val candidate = File(current, "fixtures/legacy-mobile/$name")
            if (candidate.isFile) return candidate
            current = current.parentFile
        }
        error("S0 frozen fixture not found")
    }
    private fun data(name: String = "legacy-mobile-standard-standard-v1.zip"): Map<String, ByteArray> =
        ZipFile(fixture(name)).use { zip -> zip.entries().asSequence().associate { it.name to zip.getInputStream(it).use(InputStream::readBytes) } }

    private fun safeFull(): Pair<BackupManifest, Map<String, ByteArray>> {
        val input = data()
        val manifest = ManifestCodec.decode(input.getValue("manifest.json").toString(Charsets.UTF_8))
        val oldAudit = manifest.coverage!!.domains.getValue("audit")
        val auditAbsent = oldAudit.copy(status = CoverageStatus.ABSENT, paths = emptyList(), fileCount = 0, totalSize = 0)
        return manifest.copy(
            payload = manifest.payload.copy(files = manifest.files.filterNot { it.path == "databases/audit.db" }),
            coverage = manifest.coverage!!.copy(domains = manifest.coverage!!.domains + ("audit" to auditAbsent)),
        ) to (input - "databases/audit.db")
    }

    private fun catalog(input: Map<String, ByteArray>) = ArchiveCatalog(input.map { ArchiveEntry(it.key, ArchiveEntryKind.FILE, it.value.size.toLong()) })
    private fun proofs(manifest: BackupManifest, input: Map<String, ByteArray>) =
        (manifest.files.map { it.path } + manifest.assets.filterNot { it.isDirectory }.map { it.relativePath }).mapNotNull { path ->
            input[path]?.let { ShaEvidence(path, it.size.toLong(), digest(it)) }
        }
    private fun plan(manifest: BackupManifest, input: Map<String, ByteArray>, free: Long = Long.MAX_VALUE): RestorePlan =
        RestorePlanner.plan(manifest, catalog(input), proofs(manifest, input), free, "0".repeat(64))

    private class FakeArchive(private val content: Map<String, ByteArray>, private val sizes: Map<String, Long> = emptyMap()) : RestoreArchive {
        override fun inspect() = ArchiveCatalog(content.map { (path, bytes) -> ArchiveEntry(path, ArchiveEntryKind.FILE, sizes[path] ?: bytes.size.toLong()) })
        override fun open(path: String) = ByteArrayInputStream(content.getValue(path))
        override fun close() = Unit
    }

    /** Generated by frozen desktop e6b2657 newManifest/updateCoverage/markFull/markPartial. */
    @Test fun frozenDesktopGeneratedFullAndPartialHaveAccurateDomainPreviews() {
        for (kind in listOf("full", "partial")) {
            val manifestBytes = requireNotNull(javaClass.getResourceAsStream("/desktop-v3-$kind.json")).use { it.readBytes() }
            val files = if (kind == "full") {
                listOf("vfs", "llm_usage", "chat_v2", "mistakes").associate { "$it.db" to "sqlite:$it".toByteArray() }
            } else {
                mapOf("vfs.db" to "sqlite:vfs".toByteArray(), "assets/vfs_blobs/ab/desktop.txt" to "desktop-asset".toByteArray())
            }
            val archive = FakeArchive(files + ("manifest.json" to manifestBytes))
            val receipt = ArchivePreflight.inspect(archive, Long.MAX_VALUE)
            assertTrue(receipt.isFor(archive))
            assertEquals(21, receipt.plan.domains.size)
            if (kind == "full") {
                assertEquals(receipt.plan.problems.toString(), emptyList<RestoreProblem>(), receipt.plan.problems)
                assertTrue(receipt.plan.canStage)
            } else {
                assertEquals(listOf(RestoreProblemCode.PARTIAL_NOT_SLOTABLE), receipt.plan.problems.map { it.code })
                assertEquals(DomainAction.EXCLUDED, receipt.plan.domains.single { it.id == "database:chat_v2" }.action)
                assertFalse(receipt.plan.canStage)
            }
            assertFalse(receipt.plan.canSwitchSlot)
        }
    }

    @Test fun bothFrozenS0ArchivesPreserveAuditWithoutActivatingIt() {
        for (name in listOf("legacy-mobile-standard-standard-v1.zip", "legacy-mobile-continuity-continuity-v1.zip")) {
            val result = CheckedZipArchive(fixture(name)).use { ArchivePreflight.inspect(it, Long.MAX_VALUE).plan }
            assertEquals(name, SnapshotKind.FULL, result.snapshotKind)
            assertEquals(name, 21, result.domains.size)
            assertEquals(name, emptyList<RestoreProblem>(), result.problems)
            assertEquals(DomainAction.PRESERVE_INACTIVE, result.domains.single { it.id == "audit" }.action)
            assertEquals("legacy-import/audit.db", result.files.single { it.archivePath == "databases/audit.db" }.slotRelativePath)
            assertEquals("3.0.0", result.legacyImport?.manifestVersion)
            assertEquals("0.20.0", result.legacyImport?.appVersion)
            assertEquals(4, result.legacyImport?.schemaVersions?.size)
            assertEquals("databases/chat_v2.db", result.files.single { it.archivePath == "chat_v2.db" }.slotRelativePath)
            assertEquals("databases/mistakes.db", result.files.single { it.archivePath == "mistakes.db" }.slotRelativePath)
            assertEquals("databases/llm_usage.db", result.files.single { it.archivePath == "llm_usage.db" }.slotRelativePath)
            assertTrue(result.files.any { it.archivePath.startsWith("assets/vfs_blobs/") && it.slotRelativePath.startsWith("vfs_blobs/") })
            assertTrue(result.canStage)
            assertFalse(result.canSwitchSlot)
            assertTrue(result.requiresPreservingUnmappedContent)
        }
    }

    @Test fun fullWithoutUnconsumedDomainsCanStageButCannotSwitch() {
        val (manifest, input) = safeFull()
        val result = plan(manifest, input)
        assertEquals(result.problems.toString(), emptyList<RestoreProblem>(), result.problems)
        assertFalse(result.canStage) // Pure evidence cannot mint a preflight receipt.
        assertFalse(result.canSwitchSlot)
        assertEquals(5, result.files.size)
        assertEquals(manifest.files.sumOf { it.size } * 2, result.requiredBytes)
        assertEquals(RestoreProblemCode.INSUFFICIENT_SPACE, plan(manifest, input, result.requiredBytes!! - 1).problems.single().code)
    }

    @Test fun partialPreviewPreservesOmittedDomainAndCannotSwitch() {
        val (base, input) = safeFull()
        val id = "database:chat_v2"
        val before = base.coverage!!.domains.getValue(id)
        val excluded = before.copy(status = CoverageStatus.EXCLUDED, paths = emptyList(), fileCount = 0, totalSize = 0)
        val partial = base.copy(
            snapshot = base.snapshot.copy(kind = SnapshotKind.PARTIAL_OVERLAY, requiredComponents = emptyList(), includedComponents = base.includedComponents - id),
            payload = base.payload.copy(files = base.files.filterNot { it.databaseId == "chat_v2" }),
            coverage = base.coverage!!.copy(domains = base.coverage!!.domains + (id to excluded)),
        )
        val result = plan(partial, input - "chat_v2.db")
        assertEquals(DomainAction.EXCLUDED, result.domains.single { it.id == id }.action)
        assertTrue(result.problems.any { it.code == RestoreProblemCode.PARTIAL_NOT_SLOTABLE })
        assertTrue(result.requiresPreservingUnmappedContent)
        assertFalse(result.canStage)
        assertFalse(result.canSwitchSlot)
    }

    @Test fun actualContentHashRatherThanArchiveSelfReportIsChecked() {
        val original = data()
        val path = "chat_v2.db"
        val changed = original.getValue(path).clone().also { it[100] = (it[100].toInt() xor 1).toByte() }
        val result = ArchivePreflight.inspect(FakeArchive(original + (path to changed)), Long.MAX_VALUE).plan
        assertTrue(result.problems.any { it.code == RestoreProblemCode.HASH_MISMATCH && it.archivePath == path })
        assertFalse(result.canStage)
    }

    @Test fun detectsMissingUnverifiedPathsAndConflictingTargets() {
        val (base, input) = safeFull()
        val noDb = plan(base, input - "chat_v2.db")
        assertTrue(noDb.problems.any { it.code == RestoreProblemCode.MISSING_ARCHIVE_ENTRY })
        assertTrue(noDb.problems.any { it.code == RestoreProblemCode.UNVERIFIED_FILE })
        val blob = base.files.single { it.path.startsWith("assets/vfs_blobs/") }
        val alias = blob.path.removePrefix("assets/")
        val coverage = base.coverage!!.domains.getValue("asset-root:vfs_blobs")
        val changed = base.copy(
            payload = base.payload.copy(files = base.files + blob.copy(path = alias)),
            coverage = base.coverage!!.copy(domains = base.coverage!!.domains + ("asset-root:vfs_blobs" to coverage.copy(paths = coverage.paths + alias, fileCount = 2, totalSize = coverage.totalSize * 2))),
        )
        val result = plan(changed, input + (alias to input.getValue(blob.path)))
        assertTrue(result.problems.toString(), result.problems.any { it.code == RestoreProblemCode.TARGET_CONFLICT })
        assertFalse(result.canStage)
    }

    @Test fun rejectsTraversalMissingDomainsComponentMismatchAndOverflow() {
        val (base, input) = safeFull()
        val traversal = base.copy(payload = base.payload.copy(files = base.files + BackupFile("../escape", 1, "0".repeat(64))))
        assertTrue(plan(traversal, input).problems.any { it.code == RestoreProblemCode.INVALID_ARCHIVE_PATH })
        val missing = base.copy(coverage = base.coverage!!.copy(domains = base.coverage!!.domains - "database:vfs"))
        assertTrue(plan(missing, input).problems.any { it.code == RestoreProblemCode.MISSING_DOMAIN })
        assertTrue(plan(base.copy(snapshot = base.snapshot.copy(includedComponents = emptyList())), input).problems.any { it.code == RestoreProblemCode.INCONSISTENT_COMPONENTS })
        val huge = base.copy(payload = base.payload.copy(files = base.files.mapIndexed { i, f -> if (i == 0) f.copy(size = Long.MAX_VALUE) else f }))
        assertTrue(plan(huge, input).problems.any { it.code == RestoreProblemCode.SPACE_OVERFLOW })
    }

    @Test fun unknownAndroidTargetAndExecutableDomainsAreNeverAutoCopied() {
        val (base, input) = safeFull()
        val path = "assets/workspaces/agents/example.js"
        val bytes = "hello".toByteArray()
        val f = BackupFile(path, bytes.size.toLong(), digest(bytes))
        val old = base.coverage!!.domains.getValue("agents")
        val updated = old.copy(status = CoverageStatus.COMPLETE, paths = listOf(path), fileCount = 1, totalSize = bytes.size.toLong())
        val m = base.copy(payload = base.payload.copy(files = base.files + f), coverage = base.coverage!!.copy(domains = base.coverage!!.domains + ("agents" to updated)))
        val result = plan(m, input + (path to bytes))
        assertEquals(DomainAction.EXPLICIT_TRUST_REQUIRED, result.domains.single { it.id == "agents" }.action)
        assertTrue(result.files.none { it.archivePath == path })
        assertFalse(result.canStage)
    }

    @Test fun vfsAssetCannotRedirectOrChangeItsSuffix() {
        val (base, input) = safeFull()
        val bytes = "x".toByteArray()
        for (destination in listOf("databases/runtime.db", "vfs_blobs/different")) {
            val asset = BackupAsset("vfs_blobs", "assets/vfs_blobs/safe", destination, 1, digest(bytes), false)
            val old = base.coverage!!.domains.getValue("asset-root:vfs_blobs")
            val next = old.copy(paths = old.paths + asset.relativePath, fileCount = old.fileCount + 1, totalSize = old.totalSize + 1)
            val m = base.copy(payload = base.payload.copy(assets = listOf(asset)), coverage = base.coverage!!.copy(domains = base.coverage!!.domains + ("asset-root:vfs_blobs" to next)))
            val result = plan(m, input + (asset.relativePath to bytes))
            assertTrue(result.problems.toString(), result.problems.any { it.code == RestoreProblemCode.INVALID_MANIFEST })
            assertTrue(result.files.none { it.slotRelativePath == destination })
            assertFalse(result.canStage)
        }
    }

    @Test fun catchesCaseFoldAndAncestorDestinationConflicts() {
        val (base, input) = safeFull()
        val payload = byteArrayOf(1)
        for (pair in listOf("assets/vfs_blobs/Name" to "assets/vfs_blobs/name", "assets/vfs_blobs/tree" to "assets/vfs_blobs/tree/leaf")) {
            val added = listOf(pair.first, pair.second).map { BackupFile(it, 1, digest(payload)) }
            val old = base.coverage!!.domains.getValue("asset-root:vfs_blobs")
            val next = old.copy(paths = old.paths + added.map { it.path }, fileCount = old.fileCount + 2, totalSize = old.totalSize + 2)
            val m = base.copy(payload = base.payload.copy(files = base.files + added), coverage = base.coverage!!.copy(domains = base.coverage!!.domains + ("asset-root:vfs_blobs" to next)))
            val result = plan(m, input + added.associate { it.path to payload })
            assertTrue(result.problems.toString(), result.problems.any { it.code == RestoreProblemCode.TARGET_CONFLICT })
        }
    }

    @Test fun insufficientSpacePreventsAnyPayloadRead() {
        val original = data()
        val opened = mutableListOf<String>()
        val source = object : RestoreArchive {
            override fun inspect() = catalog(original)
            override fun open(path: String): InputStream { opened += path; return ByteArrayInputStream(original.getValue(path)) }
            override fun close() = Unit
        }
        val result = ArchivePreflight.inspect(source, 0)
        assertTrue(result.plan.problems.any { it.code == RestoreProblemCode.INSUFFICIENT_SPACE })
        assertEquals(listOf("manifest.json"), opened)
    }

    @Test fun preflightCancellationPropagatesAndReceiptBindsObjectIdentity() {
        val original = data()
        val source = FakeArchive(original)
        val other = FakeArchive(original)
        val receipt = ArchivePreflight.inspect(source, Long.MAX_VALUE)
        assertTrue(receipt.isFor(source))
        assertFalse(receipt.isFor(other))
        var calls = 0
        assertThrows(CancellationException::class.java) {
            ArchivePreflight.inspect(source, Long.MAX_VALUE) { if (++calls == 4) throw CancellationException("cancelled") }
        }
    }

    @Test fun realPreflightCanStageOnlyAfterReadingEveryDeclaredFile() {
        val original = data()
        val root = Json.parseToJsonElement(original.getValue("manifest.json").toString(Charsets.UTF_8)).jsonObject
        val coverage = root.getValue("coverage").jsonObject
        val domains = coverage.getValue("domains").jsonObject
        val oldAudit = domains.getValue("audit").jsonObject
        val newAudit = JsonObject(oldAudit + mapOf("status" to JsonPrimitive("absent"), "paths" to JsonArray(emptyList()), "file_count" to JsonPrimitive(0), "total_size" to JsonPrimitive(0)))
        val newDomains = JsonObject(domains + ("audit" to newAudit))
        val files = JsonArray(root.getValue("files").jsonArray.filterNot { it.jsonObject.getValue("path").jsonPrimitive.content == "databases/audit.db" })
        val revised = JsonObject(root + mapOf("files" to files, "coverage" to JsonObject(coverage + ("domains" to newDomains))))
        val changed = original - "databases/audit.db" + ("manifest.json" to revised.toString().toByteArray())
        val source = FakeArchive(changed)
        val receipt = ArchivePreflight.inspect(source, Long.MAX_VALUE)
        assertEquals(receipt.plan.problems.toString(), emptyList<RestoreProblem>(), receipt.plan.problems)
        assertTrue(receipt.isFor(source))
        assertTrue(receipt.plan.canStage)
        assertFalse(receipt.plan.canSwitchSlot)
    }

    @Test fun largeDomainUsesIndexedCoverageForEveryPayload() {
        val (base, input) = safeFull()
        val payload = byteArrayOf(3)
        val additions = (0 until 3000).map { BackupFile("assets/vfs_blobs/large/$it", 1, digest(payload)) }
        val old = base.coverage!!.domains.getValue("asset-root:vfs_blobs")
        val next = old.copy(paths = old.paths + additions.map { it.path }, fileCount = old.fileCount + additions.size, totalSize = old.totalSize + additions.size)
        val expanded = base.copy(payload = base.payload.copy(files = base.files + additions), coverage = base.coverage!!.copy(domains = base.coverage!!.domains + ("asset-root:vfs_blobs" to next)))
        val result = plan(expanded, input + additions.associate { it.path to payload })
        assertEquals(result.problems.toString(), emptyList<RestoreProblem>(), result.problems)
        assertEquals(3005, result.files.size)
    }

