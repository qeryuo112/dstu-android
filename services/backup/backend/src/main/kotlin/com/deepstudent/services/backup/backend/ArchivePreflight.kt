package com.deepstudent.services.backup.backend

import com.deepstudent.services.backup.api.*
import java.io.ByteArrayOutputStream
import java.io.InputStream
import java.nio.ByteBuffer
import java.nio.charset.CodingErrorAction
import java.security.MessageDigest
import java.util.concurrent.CancellationException

private const val MAX_MANIFEST_BYTES = 16 * 1024 * 1024

/** Cannot be constructed outside this module. Valid only for the same live read-only archive instance. */
class PreflightResult internal constructor(val plan: RestorePlan, private val archive: RestoreArchive) {
    fun isFor(archive: RestoreArchive): Boolean = this.archive === archive
}

/** Read-only orchestration: SHA evidence is generated by reading actual bytes, never ZIP metadata. */
object ArchivePreflight {
    /** Pass a callback which throws CancellationException when the surrounding job is cancelled. */
    fun inspect(archive: RestoreArchive, availableBytes: Long, checkCancelled: () -> Unit = {}): PreflightResult {
        val result = inspectPlan(archive, availableBytes, RestoreAdmission.STANDARD, checkCancelled)
        return PreflightResult(result, archive)
    }

    /** Called only on the private ZIP after the encrypted envelope has authenticated and been unsealed. */
    fun inspectAuthenticated(archive: RestoreArchive, availableBytes: Long, checkCancelled: () -> Unit = {}): PreflightResult =
        PreflightResult(inspectPlan(archive, availableBytes, RestoreAdmission.AUTHENTICATED_PACKAGE, checkCancelled), archive)

    private fun inspectPlan(
        archive: RestoreArchive, availableBytes: Long, admission: RestoreAdmission, cancel: () -> Unit,
    ): RestorePlan = try {
        inspectOrThrow(archive, availableBytes, admission, cancel)
    } catch (e: Exception) {
        rethrowCancellation(e)
        if (e is PreflightFailure) failure(e.code, e.message ?: "Preflight failed")
        else failure(RestoreProblemCode.ARCHIVE_IO, "Archive inspection failed")
    }

    private fun inspectOrThrow(
        archive: RestoreArchive, availableBytes: Long, admission: RestoreAdmission, cancel: () -> Unit,
    ): RestorePlan {
        cancel()
        val catalog = archive.inspect()
        cancel()
        validateRootManifest(catalog)
        val bytes = archive.open("manifest.json").use { readBounded(it, MAX_MANIFEST_BYTES, cancel) }
        val manifest = decodeManifest(bytes, cancel)
        val manifestHash = digest(bytes)
        val declaration = inspectDeclarations(manifest, catalog, mobile = manifest.platform == "mobile")
        val preliminary = plan(manifest, catalog, emptyList(), availableBytes, manifestHash, admission)
        if (declaration.problems.isNotEmpty() || exceedsBudget(preliminary)) return preliminary
        return inspectPayloads(archive, availableBytes, cancel, ArchiveBinding(catalog, manifest, declaration, manifestHash, admission))
    }
    private fun validateRootManifest(catalog: ArchiveCatalog) {
        val roots = catalog.entries.filter { it.path == "manifest.json" }
        if (roots.size != 1 || roots.single().kind != ArchiveEntryKind.FILE) {
            throw PreflightFailure(RestoreProblemCode.INVALID_ARCHIVE_ENTRY, "Root manifest is missing or ambiguous")
        }
    }
    private fun decodeManifest(bytes: ByteArray, cancel: () -> Unit): BackupManifest = try {
        val raw = Charsets.UTF_8.newDecoder().onMalformedInput(CodingErrorAction.REPORT).onUnmappableCharacter(CodingErrorAction.REPORT).decode(ByteBuffer.wrap(bytes)).toString()
        ManifestCodec.decode(raw, cancel).also { cancel() }
    } catch (e: Exception) {
        rethrowCancellation(e)
        throw PreflightFailure(RestoreProblemCode.INVALID_MANIFEST, "Malformed, ambiguous or non-UTF-8 manifest")
    }
    private fun exceedsBudget(plan: RestorePlan) = plan.problems.any {
        it.code == RestoreProblemCode.INSUFFICIENT_SPACE || it.code == RestoreProblemCode.SPACE_OVERFLOW
    }
    private fun inspectPayloads(
        archive: RestoreArchive, availableBytes: Long, cancel: () -> Unit, binding: ArchiveBinding,
    ): RestorePlan {
        val evidence = mutableListOf<ShaEvidence>()
        val ioProblems = mutableListOf<RestoreProblem>()
        for ((path, entry) in binding.declaration.entries) {
            cancel()
            try {
                val observed = archive.open(path).use { input -> hashObserved(path, input, entry.size, cancel) }
                evidence += observed.evidence
                if (binding.manifest.platform == "mobile" && LegacyMobile.isDatabase(path) &&
                    !LegacyMobile.validDatabase(observed.evidence.observedSize, observed.header)
                ) ioProblems += RestoreProblem(RestoreProblemCode.INVALID_DATABASE, "Invalid legacy SQLite header or size", archivePath = path)
            } catch (e: Exception) {
                rethrowCancellation(e)
                ioProblems += RestoreProblem(RestoreProblemCode.ARCHIVE_IO, "Cannot read declared payload", archivePath = path)
            }
        }
        val plan = plan(binding.manifest, binding.catalog, evidence, availableBytes, binding.manifestHash, binding.admission)
        return plan.copy(problems = plan.problems + ioProblems, canStage = plan.problems.isEmpty() && ioProblems.isEmpty())
    }

    private fun plan(
        manifest: BackupManifest, catalog: ArchiveCatalog, evidence: List<ShaEvidence>, available: Long, hash: String,
        admission: RestoreAdmission,
    ): RestorePlan = when {
        admission == RestoreAdmission.AUTHENTICATED_PACKAGE -> RestorePlanner.planAuthenticated(manifest, catalog, evidence, available, hash)
        manifest.platform == "mobile" -> RestorePlanner.planMobile(manifest, catalog, evidence, available, hash)
        else -> RestorePlanner.plan(manifest, catalog, evidence, available, hash)
    }

    private fun rethrowCancellation(error: Exception) {
        if (error is CancellationException) throw error
        if (error is InterruptedException) { Thread.currentThread().interrupt(); throw error }
    }

    private fun failure(code: RestoreProblemCode, detail: String) = RestorePlan(
        snapshotKind = null, source = RestorePlanSource(), domains = emptyList(), files = emptyList(),
        requiredBytes = null, problems = listOf(RestoreProblem(code, detail)), canStage = false,
    )

    private fun readBounded(input: InputStream, limit: Int, cancel: () -> Unit): ByteArray {
        val out = ByteArrayOutputStream()
        val buffer = ByteArray(8192)
        while (true) {
            cancel()
            val read = input.read(buffer)
            if (read == -1) break
            if (read == 0) throw IllegalStateException("zero length read")
            require(out.size().toLong() + read <= limit)
            out.write(buffer, 0, read)
        }
        return out.toByteArray()
    }

    private fun hashObserved(path: String, input: InputStream, expected: Long, cancel: () -> Unit): ObservedPayload {
        val hash = MessageDigest.getInstance("SHA-256")
        val buffer = ByteArray(64 * 1024)
        val header = ByteArray(16)
        var headerLength = 0
        var count = 0L
        while (true) {
            cancel()
            val read = input.read(buffer)
            if (read == -1) break
            if (read == 0) throw IllegalStateException("zero length read")
            count = Math.addExact(count, read.toLong())
            val take = minOf(read, header.size - headerLength)
            buffer.copyInto(header, headerLength, 0, take)
            headerLength += take
            hash.update(buffer, 0, read)
            if (count > expected) break
        }
        return ObservedPayload(ShaEvidence(path, count, hash.digest().hex()), header.copyOf(headerLength))
    }
}

private data class ObservedPayload(val evidence: ShaEvidence, val header: ByteArray)

private data class ArchiveBinding(
    val catalog: ArchiveCatalog, val manifest: BackupManifest, val declaration: Inspection,
    val manifestHash: String, val admission: RestoreAdmission,
)

internal fun digest(bytes: ByteArray): String = MessageDigest.getInstance("SHA-256").digest(bytes).hex()
internal fun ByteArray.hex(): String = joinToString("") { "%02x".format(it.toInt() and 0xff) }

private class PreflightFailure(val code: RestoreProblemCode, message: String) : Exception(message)
